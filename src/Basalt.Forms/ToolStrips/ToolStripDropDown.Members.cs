    /// <summary>An open popup resizes to fit when its items change (an item added or removed while it is shown).</summary>
    protected override void OnLayout(LayoutEventArgs levent)
    {
        base.OnLayout(levent);

        if (!IsOpen) return;

        var preferred = GetPreferredSize(Size.Empty);
        if (preferred != Size) Size = preferred;
    }

    /// <summary>
    /// A press-drag-release from whatever opened this popup (the owner
    /// button took the mouse-down, so base's own _mouseDownItem tracking
    /// never saw it) still clicks the item released over, the way a native
    /// menu or combo box list answers a single press-drag-release.
    /// </summary>
    protected override void OnMouseUp(MouseEventArgs mea)
    {
        var item = GetItemAt(mea.Location);
        var trackedHere = item is { Pressed: true };

        base.OnMouseUp(mea);

        if (!trackedHere && item is { Enabled: true, CanSelect: true })
        {
            item.PerformClick();
            OnItemClicked(new ToolStripItemClickedEventArgs(item));
        }
    }

    /// <summary>Tab has no next control to reach on a floating popup: it closes the popup instead, as Escape does.</summary>
    protected override bool ProcessDialogKey(Keys keyData)
    {
        if ((keyData & Keys.KeyCode) == Keys.Tab && (keyData & Keys.Modifiers) == Keys.None)
        {
            Close(ToolStripDropDownCloseReason.Keyboard);
            return true;
        }

        return base.ProcessDialogKey(keyData);
    }

    /// <summary>A typed mnemonic activates the matching item first, the way a native menu answers a letter key without Alt.</summary>
    protected override bool ProcessDialogChar(char charCode) => ProcessMnemonic(charCode) || base.ProcessDialogChar(charCode);

    protected internal override bool ProcessMnemonic(char charCode) => base.ProcessMnemonic(charCode);

    protected override void ScaleControl(SizeF factor, BoundsSpecified specified) => base.ScaleControl(factor, specified);

