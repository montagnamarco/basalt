    /// <summary>
    /// Opens (at the default position, as a bare <see cref="ToolStripDropDown.Show()"/> does) or
    /// closes, uncancellably: this is Hide()/the designer, not a user dismissing it. Control's own
    /// Visible state (what AccessibleObject.State and every other base member reads, since they are
    /// typed against Control, not this hiding property) is synced to the real outcome afterward --
    /// IsOpen, not the requested value, so a cancelled Opening still leaves it correctly false.
    /// </summary>
    protected override void SetVisibleCore(bool value)
    {
        if (value)
        {
            if (!IsOpen) ShowAt(DefaultShowBounds(), ComputeDirection(), OwnerControl());
        }
        else if (IsOpen)
        {
            CloseUncancellable(ToolStripDropDownCloseReason.CloseCalled);
        }

        base.SetVisibleCore(IsOpen);
    }

    protected override LayoutSettings CreateLayoutSettings(ToolStripLayoutStyle layoutStyle) =>
        // A drop-down always stacks vertically (see StacksVertically): whatever style is asked for, the
        // settings describing it are the same plain marker ToolStrip's own vertical style would get.
        base.CreateLayoutSettings(ToolStripLayoutStyle.VerticalStackWithOverflow);

