using System.Collections;
using System.Collections.Generic;
using System.ComponentModel;

namespace System.Windows.Forms;

/// <summary>
/// DataSource/DataMember/AutoGenerateColumns: resolves a CurrencyManager through the grid's own
/// BindingContext (inherited from the parent until the grid, or an ancestor, has its own) and
/// generates one column per bindable property of the resolved list's item type. Incremental
/// updates (ListChanged, Position, commit) live in DataGridView.Binding.Sync.cs; DataError and
/// DataBindingComplete live in DataGridView.Binding.Events.cs.
/// </summary>
public partial class DataGridView
{
    private object? _dataSource;
    private string _dataMember = string.Empty;
    private bool _autoGenerateColumns = true;
    private CurrencyManager? _currencyManager;
    private PropertyDescriptorCollection? _itemProperties;
    private readonly HashSet<DataGridViewColumn> _autoGeneratedColumns = [];

    [Browsable(false)]
    [EditorBrowsable(EditorBrowsableState.Advanced)]
    [DefaultValue(true)]
    public bool AutoGenerateColumns
    {
        get => _autoGenerateColumns;
        set
        {
            if (value == _autoGenerateColumns) return;

            _autoGenerateColumns = value;
            OnAutoGenerateColumnsChanged(EventArgs.Empty);

            if (_currencyManager is not null) RebindFromCurrencyManager(rebuildColumns: true, completionType: ListChangedType.Reset);
        }
    }

    [DefaultValue("")]
    public string DataMember
    {
        get => _dataMember;
        set
        {
            var resolved = value ?? string.Empty;
            if (string.Equals(resolved, _dataMember, StringComparison.Ordinal)) return;

            _dataMember = resolved;
            OnDataMemberChanged(EventArgs.Empty);
            ResolveDataSource();
        }
    }

    [DefaultValue(null)]
    public object? DataSource
    {
        get => _dataSource;
        set
        {
            // As WinForms documents: a data source must be an IList or an IListSource (IBindingList
            // and IBindingListView both already implement IList, so checking IList alone covers them).
            if (value is not null && value is not IList && value is not IListSource)
            {
                throw new ArgumentException("DataSource must be an IList or an IListSource.", nameof(value));
            }

            if (ReferenceEquals(value, _dataSource)) return;

            _dataSource = value;
            OnDataSourceChanged(EventArgs.Empty);
            ResolveDataSource();
        }
    }

    /// <summary>True once a CurrencyManager resolved: Rows then mirrors the bound list and refuses direct Add/Insert/Remove/Clear.</summary>
    internal bool IsDataBound => _currencyManager is not null;

    protected override void OnBindingContextChanged(EventArgs e)
    {
        base.OnBindingContextChanged(e);
        ResolveDataSource();
    }

    /// <summary>
    /// Called by Control.Dispose(bool) (through its own ReleaseBindings call) while the control
    /// is being disposed: unwires the CurrencyManager so a later change to the bound list never
    /// reaches this grid again, exactly as ListControl does for ListBox/ComboBox.
    /// </summary>
    /// <summary>
    /// Called by Control.Dispose(bool) (through its own ReleaseBindings call) while the control
    /// is being disposed: unwires the CurrencyManager so a later change to the bound list never
    /// reaches this grid again, exactly as ListControl does for ListBox/ComboBox.
    /// </summary>
    internal override void ReleaseBindings()
    {
        UnwireCurrencyManager();
        _currencyManager = null;

        base.ReleaseBindings();
    }

    /// <summary>Looks up (or drops) the CurrencyManager for the current DataSource/DataMember: called whenever either, or BindingContext itself, changes.</summary>
    private void ResolveDataSource()
    {
        UnwireCurrencyManager();

        var manager = _dataSource is null || BindingContext is null ? null : BindingContext[_dataSource, _dataMember] as CurrencyManager;

        _currencyManager = manager;

        if (manager is null)
        {
            ClearBoundState();
            return;
        }

        WireCurrencyManager(manager);
        RebindFromCurrencyManager(rebuildColumns: true, completionType: ListChangedType.Reset);
    }

    /// <summary>DataSource went null (or stopped resolving to a list): drop the bound rows and whatever columns this grid generated for them, keeping the user's own columns.</summary>
    private void ClearBoundState()
    {
        ClearGeneratedColumns();
        ClearBoundRows();
        _itemProperties = null;
        Invalidate();
    }

    /// <summary>Refreshes item properties and, when asked, regenerates columns, then repopulates every row from the (possibly new) list.</summary>
    private void RebindFromCurrencyManager(bool rebuildColumns, ListChangedType completionType)
    {
        _itemProperties = ResolveItemProperties();

        if (rebuildColumns) GenerateColumnsIfNeeded();

        PopulateRowsFromList();
        SyncCurrentCellFromPosition();
        OnDataBindingComplete(new DataGridViewBindingCompleteEventArgs(completionType));
    }

    /// <summary>
    /// The resolved list's bindable properties, read from ITypedList when the list provides one
    /// (a DataView's columns, which TypeDescriptor.GetProperties(itemType) cannot see) and from
    /// the item type's own properties otherwise (a plain object or a BindingList&lt;T&gt;).
    /// </summary>
    private PropertyDescriptorCollection? ResolveItemProperties()
    {
        if (_currencyManager is null) return null;

        if (_currencyManager.List is ITypedList typedList) return typedList.GetItemProperties(null);

        return _currencyManager.GetItemProperties();
    }

    /// <summary>One DataGridViewTextBoxColumn (DataGridViewCheckBoxColumn for bool) per browsable property, replacing whatever this grid generated last time.</summary>
    private void GenerateColumnsIfNeeded()
    {
        ClearGeneratedColumns();
        if (!_autoGenerateColumns || _itemProperties is null) return;

        foreach (PropertyDescriptor descriptor in _itemProperties)
        {
            if (!descriptor.IsBrowsable) continue;

            var column = CreateAutoGeneratedColumn(descriptor);
            Columns.Add(column);
            _autoGeneratedColumns.Add(column);
        }
    }

    private static DataGridViewColumn CreateAutoGeneratedColumn(PropertyDescriptor descriptor)
    {
        var isBoolean = descriptor.PropertyType == typeof(bool) || descriptor.PropertyType == typeof(bool?);
        DataGridViewColumn column = isBoolean ? new DataGridViewCheckBoxColumn() : new DataGridViewTextBoxColumn();

        column.Name = descriptor.Name;
        column.DataPropertyName = descriptor.Name;
        column.HeaderText = descriptor.DisplayName;
        column.ValueType = descriptor.PropertyType;
        column.ReadOnly = descriptor.IsReadOnly;

        return column;
    }

    /// <summary>Removes only the columns this grid generated itself, leaving whatever the user added alone.</summary>
    private void ClearGeneratedColumns()
    {
        if (_autoGeneratedColumns.Count == 0) return;

        foreach (var column in _autoGeneratedColumns) Columns.Remove(column);
        _autoGeneratedColumns.Clear();
    }
}
