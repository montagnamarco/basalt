namespace Basalt.Data.Sessions;

/// <summary>PostgreSQL's table scripts: identity columns, ALTER COLUMN ... TYPE, and transactional DDL.</summary>
public sealed class PostgreSqlTableScripts : TableScriptGenerator
{
    private static readonly string[] Types =
    [
        "integer", "bigint", "smallint", "boolean", "numeric(18,2)", "real", "double precision", "money",
        "date", "time", "timestamp", "timestamptz", "interval", "char(10)", "varchar(50)", "text",
        "bytea", "uuid", "json", "jsonb", "xml",
    ];

    private static ScriptTransaction Transaction { get; } = new("BEGIN;", "COMMIT;", "ROLLBACK;");

    public PostgreSqlTableScripts()
        : base(new PostgreSqlDialect())
    {
    }

    public override DatabaseKind Kind => DatabaseKind.PostgreSql;

    public override IReadOnlyList<string> CommonTypes => Types;

    public override TableScript Create(TableDesign design)
    {
        var lines = design.Columns.Select(c => "    " + ColumnDefinition(c)).ToList();
        var key = design.KeyColumns;

        if (key.Count > 0)
            lines.Add($"    CONSTRAINT {Q(design.Name.Name + "_pkey")} PRIMARY KEY ({QuotedList(key.Select(c => c.Name), Q)})");

        foreach (var foreign in design.ForeignKeys)
            lines.Add("    " + ForeignKeyClause(foreign));

        return Plain([$"CREATE TABLE {Table(design)} (\n{string.Join(",\n", lines)}\n);"], Transaction);
    }

    public override TableScript Alter(TableDesign original, TableDesign edited)
    {
        var diff = TableDiff.Between(original, edited);

        if (!diff.HasChanges) return TableScript.None;

        var table = Table(edited);
        var statements = new List<string>();
        var oldKey = original.Indexes.FirstOrDefault(i => i.IsPrimaryKey);

        if (diff.KeyChanged && oldKey is not null)
            statements.Add($"ALTER TABLE {table} DROP CONSTRAINT {Q(oldKey.Name)};");

        foreach (var column in diff.Dropped)
            statements.Add($"ALTER TABLE {table} DROP COLUMN {Q(column.Name)};");

        foreach (var change in diff.Changed)
        {
            var name = Q(change.After.Name);

            if (change.Renamed)
                statements.Add($"ALTER TABLE {table} RENAME COLUMN {Q(change.Before.Name)} TO {name};");

            if (change.TypeChanged)
            {
                var type = change.After.DataType.Trim();

                // USING makes the conversion explicit; without it PostgreSQL refuses most changes of type.
                statements.Add($"ALTER TABLE {table} ALTER COLUMN {name} TYPE {type} USING {name}::{type};");
            }

            if (change.NullabilityChanged)
                statements.Add($"ALTER TABLE {table} ALTER COLUMN {name} {(change.After.IsNullable ? "DROP" : "SET")} NOT NULL;");

            if (change.DefaultChanged)
            {
                statements.Add(change.After.DefaultValue?.Trim() is { Length: > 0 } fallback
                    ? $"ALTER TABLE {table} ALTER COLUMN {name} SET DEFAULT {fallback};"
                    : $"ALTER TABLE {table} ALTER COLUMN {name} DROP DEFAULT;");
            }

            if (change.IdentityChanged)
            {
                statements.Add(change.After.IsIdentity
                    ? $"ALTER TABLE {table} ALTER COLUMN {name} ADD GENERATED BY DEFAULT AS IDENTITY;"
                    : $"ALTER TABLE {table} ALTER COLUMN {name} DROP IDENTITY IF EXISTS;");
            }
        }

        foreach (var column in diff.Added)
            statements.Add($"ALTER TABLE {table} ADD COLUMN {ColumnDefinition(column)};");

        var key = edited.KeyColumns;

        if (diff.KeyChanged && key.Count > 0)
        {
            statements.Add(
                $"ALTER TABLE {table} ADD CONSTRAINT {Q(edited.Name.Name + "_pkey")} PRIMARY KEY ({QuotedList(key.Select(c => c.Name), Q)});");
        }

        return Plain(statements, Transaction, retypes: diff.Changed.Any(c => c.TypeChanged));
    }

    private string ColumnDefinition(DesignColumn column)
    {
        var text = $"{Q(column.Name)} {column.DataType.Trim()}";

        if (column.IsIdentity) text += " GENERATED BY DEFAULT AS IDENTITY";

        if (!column.IsNullable || column.IsPrimaryKey) text += " NOT NULL";

        if (column.DefaultValue?.Trim() is { Length: > 0 } fallback)
            text += " DEFAULT " + fallback;

        return text;
    }
}
